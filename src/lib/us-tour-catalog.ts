/** Full USA starter catalog (NYC existing slugs preserved). */
export const catalogTours: CatalogTour[] = [...newYorkTours, ...usaCityTours];

export function listTourMetros(): TourMetro[] {
  return tourMetros;
}

export function getCatalogTour(slug: string) {
  return catalogTours.find((tour) => tour.slug === slug);
}

export function getToursByCity(citySlug: string) {
  if (citySlug === "all") return catalogTours;
  return catalogTours.filter((tour) => tour.citySlug === citySlug);
}

export function catalogStats() {
  const byCity = tourMetros.map((metro) => ({
    ...metro,
    count: catalogTours.filter((t) => t.citySlug === metro.slug).length,
  }));
  return {
    total: catalogTours.length,
    cities: byCity.length,
    byCity,
  };
}
