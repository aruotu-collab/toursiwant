function cityBlock(
  citySlug: string,
  cityName: string,
  stateCode: string,
  items: Array<
    Omit<
      CatalogTour,
      | "citySlug"
      | "cityName"
      | "stateCode"
      | "source"
      | "schedule"
      | "weekdays"
      | "spacesDefault"
      | "joinable"
    > &
      Partial<
        Pick<
          CatalogTour,
          "schedule" | "weekdays" | "spacesDefault" | "joinable" | "source"
        >
      >
  >,
): CatalogTour[] {
  return items.map((item) =>
    t({
      ...item,
      citySlug,
      cityName,
      stateCode,
    }),
  );
}

